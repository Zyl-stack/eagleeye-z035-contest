#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd -- "$SCRIPT_DIR/../../.." && pwd)
XSA="$ROOT/hardware/system_wrapper.xsa"
BIT="$ROOT/hardware/system_wrapper.bit"
INTEGRATION="$ROOT/integration/linux_ov5640_picodet"
BUILD_ROOT=${BUILD_ROOT:-"/home/${USER}/eagleeye_ax7020_build"}
PROJECT=${PROJECT:-"$BUILD_ROOT/eagleeye_petalinux_2022_2"}
OUTPUT=${OUTPUT:-"$ROOT/deliverables"}

for tool in petalinux-create petalinux-config petalinux-build petalinux-package; do
  command -v "$tool" >/dev/null || {
    echo "ERROR: $tool is unavailable. Source PetaLinux 2022.2 settings.sh first." >&2
    exit 1
  }
done

if [[ "${PETALINUX_VER:-}" != "2022.2" ]]; then
  echo "ERROR: system_wrapper.xsa was generated by Vivado 2022.2." >&2
  echo "       PetaLinux 2017.4 accepts HDF, not this XSA. Use PetaLinux 2022.2." >&2
  exit 1
fi
if ! unzip -p "$XSA" xsa.json | grep -q '"generatedVersion"[[:space:]]*:[[:space:]]*"2022.2"'; then
  echo "ERROR: XSA metadata is not Vivado 2022.2" >&2
  exit 1
fi

EXPECTED_BIT=bc5d35a5a414006309d0057ad6b99277847bd2f9e25162e99c92ea38d9336ed0
ACTUAL_BIT=$(sha256sum "$BIT" | awk '{print $1}')
if [[ "$ACTUAL_BIT" != "$EXPECTED_BIT" ]]; then
  echo "ERROR: supplied bitstream SHA256 mismatch: $ACTUAL_BIT" >&2
  exit 1
fi
TMP_XSA=$(mktemp -d)
trap 'rm -rf -- "$TMP_XSA"' EXIT
unzip -q "$XSA" system_wrapper.bit -d "$TMP_XSA"
EMBEDDED_BIT=$(sha256sum "$TMP_XSA/system_wrapper.bit" | awk '{print $1}')
if [[ "$EMBEDDED_BIT" != "$EXPECTED_BIT" ]]; then
  echo "ERROR: XSA embedded bitstream does not match the delivered .bit" >&2
  exit 1
fi

mkdir -p "$BUILD_ROOT" "$(dirname "$PROJECT")"
if [[ ! -f "$PROJECT/project-spec/configs/config" ]]; then
  if [[ -e "$PROJECT" ]]; then
    echo "ERROR: refusing to replace non-PetaLinux path: $PROJECT" >&2
    exit 1
  fi
  (cd "$(dirname "$PROJECT")" && petalinux-create --type project --template zynq \
    --name "$(basename "$PROJECT")")
fi

HW_DIR="$BUILD_ROOT/hw-description"
mkdir -p "$HW_DIR"
cp -f "$XSA" "$HW_DIR/system_wrapper.xsa"
(cd "$PROJECT" && petalinux-config --get-hw-description="$HW_DIR" --silentconfig)

DT_DIR="$PROJECT/project-spec/meta-user/recipes-bsp/device-tree/files"
mkdir -p "$DT_DIR"
cp -f "$INTEGRATION/petalinux/system-user.dtsi" "$DT_DIR/system-user.dtsi"

KERNEL_RECIPE="$PROJECT/project-spec/meta-user/recipes-kernel/linux"
mkdir -p "$KERNEL_RECIPE/files"
cp -f "$INTEGRATION/petalinux/eagleeye-kernel.cfg" \
  "$KERNEL_RECIPE/files/eagleeye-kernel.cfg"
cat > "$KERNEL_RECIPE/linux-xlnx_%.bbappend" <<'EOF'
FILESEXTRAPATHS:prepend := "${THISDIR}/files:"
SRC_URI += "file://eagleeye-kernel.cfg"
EOF

(cd "$PROJECT" && petalinux-build)
(cd "$PROJECT" && petalinux-package --boot \
  --fsbl images/linux/zynq_fsbl.elf \
  --fpga "$BIT" \
  --u-boot --force)

mkdir -p "$OUTPUT/images" "$OUTPUT/device-tree" "$OUTPUT/logs"
cp -f "$PROJECT/images/linux/BOOT.BIN" "$OUTPUT/images/BOOT.BIN"
cp -f "$PROJECT/images/linux/image.ub" "$OUTPUT/images/image.ub"
cp -f "$INTEGRATION/petalinux/system-user.dtsi" \
  "$OUTPUT/device-tree/system-user.dtsi"
cp -f "$INTEGRATION/petalinux/eagleeye-kernel.cfg" \
  "$OUTPUT/device-tree/eagleeye-kernel.cfg"
if [[ -f "$PROJECT/images/linux/system.dtb" ]]; then
  cp -f "$PROJECT/images/linux/system.dtb" "$OUTPUT/device-tree/system.dtb"
fi
sha256sum "$OUTPUT/images/BOOT.BIN" "$OUTPUT/images/image.ub" \
  > "$OUTPUT/images/SHA256SUMS"
echo "Built images are in $OUTPUT/images"
